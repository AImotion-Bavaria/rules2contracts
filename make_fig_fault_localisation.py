#!/usr/bin/env python3
"""Export the fault-localisation trace data for the paper's Fig. "F6".

Reconstructs one perception-fault episode from the RQ4 sweep (scenario,
ego/lead pair and injection mode are fixed below so the figure is
reproducible), evaluates the contract monitors of the valid R_G1 document,
and writes per-step data for the figure: the ground-truth gap and its
faulty perception estimate, the rule threshold, the injected fault window,
and the robustness of the system guarantee and of the Perception
guarantee/assumption -- the signals from which the monitors derive
system-violation and culpability verdicts.

Output: data/fig_fault_localisation.dat,
        data/fig_fault_localisation_macros.tex (episode-specific
        numbers quoted in the caption/text: culpability onset, violation
        onset, and the early-warning lead), and
        data/fig_fault_scene_generated.tex (bird's-eye snapshot of
        the recorded traffic at the violation onset, in the ego frame, as
        \\FaultSceneVehicle{x}{y}{angle}{length}{width}{style} calls consumed
        by figures/fig_fault_scene.tex).
Pipeline: scenarios/ + contracts/R_G1.yaml -> this script -> pdflatex.
"""

import math
import pathlib
import sys

import yaml

from commonroad_traces import (find_following_pairs, ground_truth,
                               load_scenario, synthesise_features)
from monitor_backend import RuleMonitor

SCENARIO = pathlib.Path("scenarios/USA_US101-20_1_T-1.xml")
EGO, LEAD = "527", "523"          # following episode of the RQ4 sweep
MODE = "perception_fault"
RULE = pathlib.Path("contracts/R_G1.yaml")
OUT = pathlib.Path("data/fig_fault_localisation.dat")
if "--out-dir" in sys.argv:  # optional: write elsewhere (reproduction runs)
    OUT = pathlib.Path(sys.argv[sys.argv.index("--out-dir") + 1]) / OUT.name
    OUT.parent.mkdir(parents=True, exist_ok=True)


def main() -> None:
    constants = {k: float(v)
                 for k, v in yaml.safe_load(RULE.read_text())["constants"].items()}
    scenario = load_scenario(SCENARIO)
    pair = next(p for p in find_following_pairs(scenario)
                if p["ego"] == EGO and p["lead"] == LEAD)
    gt = ground_truth(scenario, pair)
    trace = synthesise_features(gt, constants, MODE)

    # recover the injected fault window the same way synthesise_features
    # derives it (bias exceeds the contract bound only inside the window)
    eps_d = constants["EPS_D"]
    fault = [1 if abs(trace["d_lead"][t] - trace["d_gap"][t]) > eps_d else 0
             for t in gt["time"]]

    monitor = RuleMonitor(RULE)
    res = monitor.evaluate(trace)
    rob = {name: dict(series) for name, series in
           [("sysG", res["system"]["guarantee"]),
            ("percG", res["Perception"]["guarantee"]),
            ("percA", res["Perception"]["assumption"])]}

    tau = constants["TAU"]
    with OUT.open("w") as f:
        f.write("t d_gap d_lead thr_sys hazard fault "
                "rob_sysG rob_percG rob_percA\n")
        for t in gt["time"]:
            f.write(f"{t} {trace['d_gap'][t]:.2f} {trace['d_lead'][t]:.2f} "
                    f"{tau * trace['v_true'][t]:.2f} "
                    f"{trace['hazard_on'][t]:.0f} {fault[t]} "
                    f"{rob['sysG'][t]:.3f} {rob['percG'][t]:.3f} "
                    f"{rob['percA'][t]:.3f}\n")
    viol = [t for t in gt["time"] if rob["sysG"][t] < 0]
    culp = [t for t in gt["time"]
            if rob["percG"][t] < 0 and rob["percA"][t] >= 0]
    lead = viol[0] - culp[0]

    # bird's-eye snapshot at the violation onset, in the ego frame
    # (x = longitudinal, y = lateral); vehicles within the plot window
    t_snap = pair["steps"][viol[0]]  # recorded step of the resampled index
    ex, ey, eo, _ = scenario["vehicles"][EGO]["states"][t_snap]

    def to_ego(px: float, py: float) -> tuple[float, float]:
        dx, dy = px - ex, py - ey
        return (dx * math.cos(eo) + dy * math.sin(eo),
                -dx * math.sin(eo) + dy * math.cos(eo))

    scene = OUT.with_name("fig_fault_scene_generated.tex")
    with scene.open("w") as f:
        f.write("% AUTO-GENERATED by make_fig_fault_localisation.py; "
                "do not edit.\n"
                f"% scenario {SCENARIO.name}, recorded step {t_snap} "
                f"(episode step {viol[0]}, violation onset)\n")
    # real lane geometry from the scenario's lanelets (ego frame), in a
    # separate file so the figure can clip the road without clipping the
    # vehicle boxes and gap annotations
    import xml.etree.ElementTree as ET
    root = ET.parse(SCENARIO).getroot()
    lanes = OUT.with_name("fig_fault_scene_lanes_generated.tex")
    with lanes.open("w") as f:
        f.write("% AUTO-GENERATED by make_fig_fault_localisation.py; "
                "do not edit.\n")
        for lanelet in root.findall("lanelet"):
            bounds = {}
            for side in ("leftBound", "rightBound"):
                pts = [to_ego(float(p.find("x").text), float(p.find("y").text))
                       for p in lanelet.find(side).findall("point")]
                bounds[side] = pts
            if not any(-20 <= x <= 38 and -8 <= y <= 8
                       for pts in bounds.values() for x, y in pts):
                continue
            polygon = bounds["leftBound"] + bounds["rightBound"][::-1]
            f.write("\\FaultSceneLanelet{"
                    + " ".join(f"({x:.1f},{y:.1f})" for x, y in polygon)
                    + "}\n")
            for side in ("leftBound", "rightBound"):
                f.write("\\FaultSceneLaneBound{"
                        + " ".join(f"({x:.1f},{y:.1f})"
                                   for x, y in bounds[side])
                        + "}\n")
    with scene.open("a") as f:  # vehicles, ghost, and gap annotations
        for vid, veh in scenario["vehicles"].items():
            if t_snap not in veh["states"]:
                continue
            vx, vy, vo, _ = veh["states"][t_snap]
            x, y = to_ego(vx, vy)
            if not (-16 <= x <= 34 and -6.5 <= y <= 6.5):
                continue
            # box heading = the RECORDED per-state orientation of the
            # vehicle (relative to ego heading), not a lane alignment
            ang = math.degrees((vo - eo + math.pi) % (2 * math.pi) - math.pi)
            style = {EGO: "egocar", LEAD: "leadcar"}.get(vid, "othercar")
            f.write(f"\\FaultSceneVehicle{{{x:.2f}}}{{{y:.2f}}}{{{ang:.2f}}}"
                    f"{{{veh['length']:.2f}}}{{{veh['width']:.2f}}}"
                    f"{{{style}}}\n")
        # perceived lead position (ghost) and gap annotations at the onset
        i = viol[0]
        bias = trace["d_lead"][i] - trace["d_gap"][i]
        ego_v = scenario["vehicles"][EGO]
        lead_v = scenario["vehicles"][LEAD]
        lx0, ly0, lo0, _ = lead_v["states"][t_snap]
        gx = (lx0 - ex) * math.cos(eo) + (ly0 - ey) * math.sin(eo)
        gy = -(lx0 - ex) * math.sin(eo) + (ly0 - ey) * math.cos(eo)
        gang = math.degrees((lo0 - eo + math.pi) % (2 * math.pi) - math.pi)
        f.write(f"\\FaultSceneGhost{{{gx + bias:.2f}}}{{{gy:.2f}}}"
                f"{{{gang:.1f}}}{{{lead_v['length']:.2f}}}"
                f"{{{lead_v['width']:.2f}}}\n")
        ego_front = ego_v["length"] / 2
        lead_rear = gx - lead_v["length"] / 2
        f.write(f"\\FaultSceneGap{{{ego_front:.2f}}}{{{lead_rear:.2f}}}"
                f"{{{trace['d_gap'][i]:.1f}}}\n")
        f.write(f"\\FaultSceneGhostGap{{{ego_front:.2f}}}"
                f"{{{lead_rear + bias:.2f}}}{{{trace['d_lead'][i]:.1f}}}\n")

    macros = OUT.with_name("fig_fault_localisation_macros.tex")
    macros.write_text(
        "% AUTO-GENERATED by make_fig_fault_localisation.py; do not edit.\n"
        f"\\newcommand{{\\resFsixCulpOnset}}{{{culp[0]}}}\n"
        f"\\newcommand{{\\resFsixViolOnset}}{{{viol[0]}}}\n"
        f"\\newcommand{{\\resFsixLeadSteps}}{{{lead}}}\n"
        f"\\newcommand{{\\resFsixLeadSecs}}{{{lead / 10:.1f}}}\n")
    print(f"{OUT} written: {len(gt['time'])} steps, "
          f"system violated at {viol[0]}..{viol[-1]} ({len(viol)} steps), "
          f"Perception culpable at {culp[0]}..{culp[-1]} ({len(culp)} steps), "
          f"early-warning lead {lead} steps")


if __name__ == "__main__":
    main()
